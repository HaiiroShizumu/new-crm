// RV-2 (фронтовая половина): «включён = App установлен» дополняется состоянием
// жизненного цикла установки. Серверный аналог — guard M-4 (отдельный поток).
export type SmbApplicationLifecycle =
  // статусы установки/удаления ещё запрашиваются — страницу не открываем
  | 'loading'
  // установлена, ни установка, ни удаление не запущены
  | 'idle'
  // установка идёт и не завершена
  | 'installing'
  // установка завершилась ошибкой (запись App могла остаться)
  | 'install-failed'
  // приложение удаляется
  | 'uninstalling'
  // у пользователя нет прав смотреть статусы — решает только список App
  | 'unknown';
